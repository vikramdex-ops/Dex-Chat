// Builds the guest join page (guest/page.ts and guest/page.css) and the webinar pages
// (webinar/page.ts and webinar/page.css) into src/guest-assets.gen.ts, a module of strings the
// Worker serves. Wrangler runs this before `wrangler dev` and `deploy`
// (wrangler.jsonc ▸ build), so the page is always the one in the source.
//   node scripts/build-guest.mjs
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const common = { bundle: true, minify: true, write: false, logLevel: 'warning', legalComments: 'none' };
const js = await build({ ...common, entryPoints: [path.join(root, 'guest/page.ts')], format: 'iife', target: ['chrome110', 'firefox115', 'safari16'], platform: 'browser' });
const css = await build({ ...common, entryPoints: [path.join(root, 'guest/page.css')], loader: { '.css': 'css' }, target: ['chrome110', 'firefox115', 'safari16'] });
const wjs = await build({ ...common, entryPoints: [path.join(root, 'webinar/page.ts')], format: 'iife', target: ['chrome110', 'firefox115', 'safari16'], platform: 'browser' });
const wcss = await build({ ...common, entryPoints: [path.join(root, 'webinar/page.css')], loader: { '.css': 'css' }, target: ['chrome110', 'firefox115', 'safari16'] });
const out = `// Generated by scripts/build-guest.mjs from guest/ and webinar/ (page.ts and page.css). Do not edit.
export const GUEST_JS = ${JSON.stringify(js.outputFiles[0].text)};
export const GUEST_CSS = ${JSON.stringify(css.outputFiles[0].text)};
export const WEBINAR_JS = ${JSON.stringify(wjs.outputFiles[0].text)};
export const WEBINAR_CSS = ${JSON.stringify(wcss.outputFiles[0].text)};
`;
const file = path.join(root, 'src/guest-assets.gen.ts');
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) fs.writeFileSync(file, out);
console.log(`guest page: ${(js.outputFiles[0].text.length / 1024).toFixed(1)} KB script, ${(css.outputFiles[0].text.length / 1024).toFixed(1)} KB styles; webinar pages: ${(wjs.outputFiles[0].text.length / 1024).toFixed(1)} KB script, ${(wcss.outputFiles[0].text.length / 1024).toFixed(1)} KB styles`);
