// Builds Dexterity Meet's public pages (scripts/site-assets.mjs: the landing page, the meeting, the
// webinar pages, fonts and the mark) into src/site-assets.gen.ts, a module the Worker serves them
// from, so the gateway can serve the meeting site itself (on its own address before the Pages site
// is set up, and in local tests). Wrangler runs this before `wrangler dev` and `deploy`
// (wrangler.jsonc ▸ build), so the pages are always the ones in the source.
//   node scripts/build-guest.mjs
import fs from 'node:fs';
import path from 'node:path';
import { buildSite, sizes } from './site-assets.mjs';

const root = path.resolve(import.meta.dirname, '..');
const site = await buildSite();
const entries = [...site.files].map(([name, f]) => {
  const text = /^text\/|svg/.test(f.type);
  return `  ${JSON.stringify(name)}: { type: ${JSON.stringify(f.type)}, ${text ? `text: ${JSON.stringify(f.data.toString('utf8'))}` : `b64: ${JSON.stringify(f.data.toString('base64'))}`} },`;
});
const out = `// Generated by scripts/build-guest.mjs from meet/ and webinar/. Do not edit.
export const SITE_FILES: Record<string, { type: string; text?: string; b64?: string }> = {
${entries.join('\n')}
};
export const SITE_NAMES = ${JSON.stringify(site.names)} as const;
`;
const file = path.join(root, 'src/site-assets.gen.ts');
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) fs.writeFileSync(file, out);
fs.rmSync(path.join(root, 'src/guest-assets.gen.ts'), { force: true });
console.log(`meeting site: ${sizes(site)}`);
